import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { loadAtlas } from '../js/atlas/load.js';
import { TRAILS_KEY, readSavedTrails, saveNamedTrail, removeNamedTrail, restoreNamedTrail, loadCuratedTrails, isConnectedTrail } from '../js/trail-model.js';

const root = new URL('../', import.meta.url);
globalThis.fetch = async (url) => new Response(await readFile(new URL(url, root)));
const storage = new Map();
let quota = false;
globalThis.localStorage = {
  getItem: (key) => storage.get(key) ?? null,
  setItem: (key, value) => { if (quota) throw new Error('QuotaExceededError'); storage.set(key, value); },
};
const atlas = await loadAtlas('data/');
const catalog = await loadCuratedTrails(atlas);
const path = catalog[0].path;
assert.deepEqual(readSavedTrails(), { routes: [], readonly: false });
assert.equal(saveNamedTrail(atlas, { name: ' ', path }).reason, 'name');
assert.equal(saveNamedTrail(atlas, { name: 'x'.repeat(81), path }).reason, 'name');
assert.equal(saveNamedTrail(atlas, { name: 'Missing edge', path: ['maker.arduino', 'coffee.espresso'] }).reason, 'path');
assert.equal(isConnectedTrail(atlas, [path[0], path[1], path[0]]), false);
assert.equal(isConnectedTrail(atlas, ['unknown.id', path[0]]), false);
const first = saveNamedTrail(atlas, { name: '  Coffee ideas  ', path });
assert.ok(first.ok);
assert.equal(first.route.name, 'Coffee ideas');
assert.deepEqual(first.route.path, path);
const repeated = saveNamedTrail(atlas, { name: 'Weekend', path });
assert.equal(repeated.route.id, first.route.id, 'Saving the same path updates its name rather than duplicating it');
assert.equal(readSavedTrails().routes.length, 1);
const second = saveNamedTrail(atlas, { name: 'Living worlds', path: catalog[1].path });
const renamed = saveNamedTrail(atlas, { id: first.route.id, name: '<em>My weekend</em>', path: [] });
assert.ok(renamed.ok);
assert.equal(readSavedTrails().routes[0].id, second.route.id, 'Renaming keeps the existing order');
assert.deepEqual(renamed.route.path, path, 'Renaming cannot mutate the path');
const removed = removeNamedTrail(first.route.id);
assert.ok(removed.ok);
assert.equal(readSavedTrails().routes.length, 1);
assert.ok(restoreNamedTrail(removed.removed).ok);
assert.equal(restoreNamedTrail(removed.removed).reason, 'exists');
assert.equal(removeNamedTrail('gone').reason, 'missing');
quota = true;
const before = storage.get(TRAILS_KEY);
assert.equal(saveNamedTrail(atlas, { name: 'Sound', path: catalog[2].path }).reason, 'storage');
assert.equal(removeNamedTrail(first.route.id).reason, 'storage');
assert.equal(storage.get(TRAILS_KEY), before, 'Failed writes keep every previously saved route');
quota = false;
const unavailable = { id: 'old-route', name: 'An old route', path: ['retired.one', 'retired.two'] };
storage.set(TRAILS_KEY, JSON.stringify({ v: 1, routes: [unavailable, ...readSavedTrails().routes] }));
assert.ok(saveNamedTrail(atlas, { id: unavailable.id, name: 'Keep this memory' }).ok);
assert.deepEqual(readSavedTrails().routes.find((route) => route.id === unavailable.id).path, unavailable.path);
assert.ok(saveNamedTrail(atlas, { name: 'Sound', path: catalog[2].path }).ok);
assert.ok(readSavedTrails().routes.some((route) => route.id === unavailable.id), 'Fresh writes preserve changes made by another tab');
storage.set(TRAILS_KEY, JSON.stringify({ v: 3, routes: [unavailable], unknown: 'preserve' }));
const future = storage.get(TRAILS_KEY);
assert.ok(readSavedTrails().readonly);
assert.equal(saveNamedTrail(atlas, { name: 'Future', path }).reason, 'newer');
assert.equal(removeNamedTrail(unavailable.id).reason, 'newer');
assert.equal(restoreNamedTrail(unavailable).reason, 'newer');
assert.equal(storage.get(TRAILS_KEY), future);
storage.set(TRAILS_KEY, JSON.stringify({ v: 1, routes: Array.from({ length: 50 }, (_, i) => ({ ...unavailable, id: `route-${i}` })) }));
assert.equal(saveNamedTrail(atlas, { name: 'One too many', path }).reason, 'limit');
storage.set(TRAILS_KEY, JSON.stringify({ v: 1, routes: [null, { id: 'bad' }, unavailable, unavailable] }));
assert.deepEqual(readSavedTrails().routes, [unavailable], 'Malformed and duplicate records never break the library');
assert.equal(storage.has('aficion:profile:v1'), false, 'Routes never touch the hobby profile');
console.log('PASS: named routes, connected paths, renaming, deduplication, undo, unavailable stops, quota failures, fresh storage reads and future-version protection.');
