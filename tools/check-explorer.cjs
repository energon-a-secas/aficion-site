// Optional browser acceptance check. Uses Playwright from the developer environment.
const { chromium, webkit } = require('playwright');
const assert = require('node:assert/strict');

(async () => {
  const engine = process.env.AFICION_BROWSER === 'webkit' || process.argv.includes('--webkit') ? webkit : chromium;
  const browser = await engine.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  const origin = process.env.AFICION_PREVIEW_URL || 'http://127.0.0.1:8877';
  try {
    await page.goto(origin);
    await page.locator('#exploreHeading').waitFor();
    await page.screenshot({ path: '/private/tmp/aficion-explore-desktop.png' });
    console.log('Initial:', await page.locator('#exploreHeading').innerText());
    console.log('Runtime errors:', errors);
    assert.deepEqual(errors, []);
    assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('aficion:profile:v1'))?.n?.length || 0), 0, 'First visit must not save an example');
    assert.equal(await page.locator('.ex-feature__stops a').count(), 4);
    assert.equal(await page.locator('.ex-feature__branch').count(), 2);
    await page.locator('[data-example="birds-to-galaxies"]').focus();
    await page.keyboard.press('Enter');
    assert.match(await page.locator('#featureTitle').innerText(), /distant galaxies/);
    assert.ok(await page.locator('[data-example="birds-to-galaxies"]').evaluate((el) => el === document.activeElement));
    await page.locator('[data-ex="feature-atlas"]').click();
    assert.deepEqual(await page.evaluate(async () => (await import('/js/state.js')).state.walk.journey.path), ['outdoor.birdwatching', 'core.photography', 'astro.astrophoto', 'astro.deep-sky']);
    assert.equal(await page.evaluate(async () => (await import('/js/state.js')).state.profile.n.length), 0, 'Opening the homepage example never saves its hobbies');
    await page.goBack();
    await page.locator('#featureTitle').waitFor();
    assert.equal(await page.locator('[data-example="birds-to-galaxies"]').getAttribute('aria-pressed'), 'true');
    await page.locator('.ex-feature__branch--depth').click();
    await page.locator('#exploreHeading').filter({ hasText: 'Composition' }).waitFor();
    await page.goBack();
    await page.locator('#exploreSearch').waitFor();
    await page.locator('#exploreSearch').fill('worldbuilding');
    await page.getByRole('link', { name: /Worldbuilding/ }).waitFor();
    await page.getByRole('link', { name: /Worldbuilding/ }).click();
    await page.waitForURL('**/#hobby=core.writing.worldbuilding');
    await page.locator('#exploreHeading').filter({ hasText: 'Worldbuilding' }).waitFor();
    await page.locator('.ex-detail__actions [data-ex="save"]').click();
    await page.waitForFunction(() => JSON.parse(localStorage.getItem('aficion:profile:v1'))?.n.includes('core.writing.worldbuilding'));
    await page.goBack();
    await page.locator('#exploreSearch').waitFor();
    await page.locator('#exploreSearch').fill('photography');
    await page.locator('a[href="#hobby=core.photography"]').last().click();
    await page.locator('#exploreHeading').filter({ hasText: 'Photography' }).waitFor();
    assert.equal(await page.locator('.ex-subtopics .ex-hobby').count(), 6);
    await page.screenshot({ path: '/private/tmp/aficion-hobby-desktop.png' });
    await page.locator('[data-ex="lens"][data-lens="skills"]').click();
    assert.ok(await page.locator('.ex-connection').count() > 0);
    await page.locator('[data-ex="trace"]').first().click();
    await page.locator('#atlasWorkspace').waitFor({ state: 'visible' });
    assert.ok(await page.evaluate(async () => (await import('/js/state.js')).state.tracePath.length > 1));
    const theme = await page.evaluate(async () => (await import('/js/atlas/theme.js')).resolveTheme());
    assert.notEqual(theme.nodeCore, theme.bg, 'Reduced motion must not collapse all canvas colours');
    await page.screenshot({ path: '/private/tmp/aficion-atlas-desktop.png' });
    await page.locator('[data-act="trace-clear"]').click();
    await page.locator('#searchInput').fill('worldbuilding');
    await page.locator('#searchResults [data-node="core.writing.worldbuilding"]').click();
    await page.locator('#innerOverlay').waitFor({ state: 'visible' });
    await page.locator('#innerClose').click();
    await page.locator('[data-view="mine"]').click();
    await page.locator('.ex-hobby').waitFor();
    assert.equal(await page.locator('.ex-hobby').count(), 1);
    await page.reload();
    await page.locator('.ex-hobby').waitFor();
    assert.match(await page.locator('.ex-hobby').innerText(), /Worldbuilding/);
    await page.locator('#btnShare').click();
    await page.waitForFunction(() => document.getElementById('shareUrl').value.includes('#p='));
    const shared = await page.locator('#shareUrl').inputValue();
    const second = await context.newPage();
    await second.goto(shared.replace(/^https?:\/\/[^/]+/, origin));
    await second.locator('#atlasCanvas').waitFor({ state: 'visible' });
    await second.close();
    await page.locator('#shareModal button[data-modal-close]').first().click();
    await page.locator('[data-view="explore"]').click();
    await page.locator('#appMore summary').click();
    await page.locator('#btnBuilds').click();
    await page.locator('[data-act="build-open"]').first().click();
    await page.locator('#atlasWorkspace').waitFor({ state: 'visible' });
    await page.locator('#buildPanel').waitFor({ state: 'visible' });
    await page.locator('[data-act="build-close"]').first().click();
    await page.locator('[data-view="explore"]').click();
    await page.locator('#appMore summary').click();
    await page.locator('#btnHelp').click();
    await page.locator('[data-act="tour-open"]').click();
    await page.locator('#tourOverlay').waitFor({ state: 'visible' });
    await page.locator('[data-act="tour-skip"]').click();
    await page.locator('[data-view="explore"]').click();
    await page.locator('[data-filter="deep"]').click();
    assert.ok(await page.locator('.ex-depth').count() > 0);
    await page.locator('#exploreSearch').fill('zzzz-no-hobby');
    await page.locator('.ex-empty').waitFor();
    assert.match(await page.locator('.ex-empty').innerText(), /No hobbies/);
    const mobile = await context.newPage({ viewport: { width: 390, height: 844 } });
    await mobile.setViewportSize({ width: 390, height: 844 });
    await mobile.goto(origin);
    await mobile.locator('#exploreHeading').waitFor();
    await mobile.screenshot({ path: '/private/tmp/aficion-explore-mobile.png' });
    assert.ok(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'No horizontal page overflow');
    assert.ok(await mobile.locator('#exploreFeature').isVisible(), 'The homepage example remains available on mobile');
    assert.ok(await mobile.evaluate(() => {
      const search = document.getElementById('exploreSearch'), feature = document.getElementById('exploreFeature');
      return search.getBoundingClientRect().top < feature.getBoundingClientRect().top && !!(search.compareDocumentPosition(feature) & Node.DOCUMENT_POSITION_FOLLOWING);
    }), 'Mobile search comes before the example visually and in reading order');
    await mobile.locator('#exploreSearch').fill('guitar');
    await mobile.locator('#exploreFeature').waitFor({ state: 'hidden' });
    await mobile.locator('a[href="#hobby=music.guitar"]').click();
    await mobile.locator('#exploreHeading').filter({ hasText: 'Guitar' }).waitFor();
    await mobile.screenshot({ path: '/private/tmp/aficion-hobby-mobile.png' });
    await mobile.locator('.ex-detail__actions [data-ex="save"]').click();
    await mobile.locator('[data-view="mine"]').click();
    await mobile.locator('.ex-hobby').first().waitFor();
    assert.equal(await mobile.locator('.ex-hobby').count(), 2);
    await mobile.goto(origin + '/?lang=es#hobby=core.photography');
    await mobile.locator('#exploreHeading').filter({ hasText: 'Fotografía' }).waitFor();
    assert.equal(await mobile.locator('.ex-subtopics .ex-hobby').count(), 6);
    await mobile.screenshot({ path: '/private/tmp/aficion-spanish-mobile.png' });
    await mobile.locator('#langBtn').click();
    await mobile.locator('#exploreHeading').filter({ hasText: 'Photography' }).waitFor();
    await mobile.setViewportSize({ width: 320, height: 740 });
    assert.ok(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'No overflow at 320px');
    await mobile.close();
    const failure = await context.newPage();
    await failure.route('**/data/atlas.json', (route) => route.abort());
    await failure.goto(origin);
    await failure.getByRole('heading', { name: 'The hobby atlas could not load' }).waitFor();
    await failure.close();
    const failedInner = await context.newPage();
    await failedInner.route('**/inner/core.photography.json', (route) => route.abort());
    await failedInner.goto(origin + '/#hobby=core.photography.composition');
    await failedInner.getByRole('heading', { name: 'The subtopics could not load.' }).waitFor();
    await failedInner.unroute('**/inner/core.photography.json');
    await failedInner.getByRole('link', { name: 'Try again' }).click();
    await failedInner.locator('#exploreHeading').filter({ hasText: 'Composition' }).waitFor();
    await failedInner.close();
    const partial = await context.newPage();
    await partial.route('**/search-index.json', (route) => route.abort());
    await partial.goto(origin);
    await partial.locator('#exploreHeading').waitFor();
    await partial.locator('.ex-load-note').waitFor();
    assert.ok(await partial.locator('.ex-categories a').count() > 0);
    await partial.close();
    assert.deepEqual(errors, []);
    console.log('PASS: first visit, subtopic search, deep links, saving, history, reload, connections, share, filters, empty states, mobile and Spanish.');
  } finally {
    await browser.close();
  }
})().catch((error) => { console.error(error); process.exitCode = 1; });
